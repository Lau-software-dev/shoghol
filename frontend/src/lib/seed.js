/** YYYY-MM-DD, `offset` days from today, in local time (the way format.js reads dates back). */
function day(offset) {
  const d = new Date()
  d.setDate(d.getDate() + offset)
  return [d.getFullYear(), d.getMonth() + 1, d.getDate()].map((n) => String(n).padStart(2, '0')).join('-')
}

